'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),{execFileSync}=require('node:child_process');
test('current isolated preview uses clean-sheet save keys, v15 and never loads account services',()=>{
 const out=execFileSync(process.execPath,['scripts/prepare-automatic-preview.mjs'],{encoding:'utf8'}).trim();
 const dir=out.slice('Isolated automatic RPG preview: '.length);
 assert(out.startsWith('Isolated automatic RPG preview: '));
 const html=fs.readFileSync(path.join(dir,'index.html'),'utf8'),save=fs.readFileSync(path.join(dir,'online/v012-save.js'),'utf8');
 assert(html.includes('globalThis.__WANDERER_CLOUD_ONLY__=false;'));
 assert(html.includes('const PHASE5_VALIDATION=true;'));
 for(const file of ['v012-auth-bootstrap.js','v012-account.mjs','v012-feedback.mjs','v012-leaderboard-ui.mjs'])assert(!html.includes('src="online/'+file));
 assert(save.includes("PREFIX='wanderer_automatic_rpg_preview_c2_v1_'"));
 assert(!fs.existsSync(path.join(dir,'online/firebase-client.mjs')));
 assert(fs.existsSync(path.join(dir,'combat/talent-catalog.js')));
 assert(!html.includes('src="combat/automatic-talents.js"'));
 const refs=[...html.matchAll(/(?:src|href)="([^"#?]+)(?:\?[^\"]*)?"/g)].map(x=>x[1]).filter(x=>/^(online|combat|economy|assets)\//.test(x)&&!x.includes("'"));
 assert.deepEqual(refs.filter(x=>!fs.existsSync(path.join(dir,x))),[],'all active referenced files must exist');
 const oldKey='wanderer_v012_endless_v1_local',storage=new Map([[oldKey,'untouched production-like data']]);
 const create=require('./v012-economy-harness.cjs');
 const game=create(17,html,{}, {root:dir,validationStorage:storage});
 assert.equal(game.debug().phase5Ready,true);
 assert.equal(game.state().automaticTalents.treeVersion,15);
 game.start(1,true);
 assert.equal(game.controller().state.dungeon.cards.length,3);
 const card=game.controller().state.dungeon.cards[0];
 game.controller().chooseRealm(card.id);
 assert(game.controller().visitRoom(1));
 assert.equal(game.enter(),true);
 const checkpointKeys=[...storage.keys()].filter(key=>key.startsWith('wanderer_automatic_rpg_preview_c2_v1_'));
 assert(checkpointKeys.length>0,'Current checkpoint stored in isolated preview namespace');
 assert.equal(storage.get(oldKey),'untouched production-like data');
 assert.equal(game.state().automaticTalents.treeVersion,15);
});
